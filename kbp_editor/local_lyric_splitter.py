from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence


def default_local_lyric_splitter_candidates() -> List[Path]:
    """Return standard Windows install locations for Local Lyric Splitter."""
    candidates: List[Path] = [
        Path(r"C:\Program Files (x86)\Local Lyric Splitter\Local Lyric Splitter.exe"),
        Path(r"C:\Program Files\Local Lyric Splitter\Local Lyric Splitter.exe"),
    ]
    local_app_data = os.environ.get("LOCALAPPDATA", "").strip()
    if local_app_data:
        candidates.append(Path(local_app_data) / "Programs" / "Local Lyric Splitter" / "Local Lyric Splitter.exe")
        candidates.append(Path(local_app_data) / "Local Lyric Splitter" / "Local Lyric Splitter.exe")
    return candidates


def find_local_lyric_splitter_exe(
    configured_path: str = "",
    candidates: Optional[Sequence[Path]] = None,
) -> Optional[Path]:
    """
    Locate Local Lyric Splitter.exe, checking any saved user path first,
    then standard install paths. Returns None if not found.
    """
    if configured_path:
        p = Path(configured_path)
        if p.is_file():
            return p

    search_list = candidates if candidates is not None else default_local_lyric_splitter_candidates()
    for cand in search_list:
        if cand.is_file():
            return cand
    return None


def build_lls_cli_command(
    exe_path: str | Path,
    artist: str,
    song: str,
    out_dir: str | Path,
    audio_path: str = "",
) -> List[str]:
    """Build the headless CLI invocation for Local Lyric Splitter."""
    audio_arg = audio_path.strip() if audio_path and audio_path.strip() else "placeholder.mp3"
    return [
        str(exe_path),
        "--artist",
        artist.strip(),
        "--song",
        song.strip(),
        "--audio",
        audio_arg,
        "--out",
        str(out_dir),
        "--silent",
    ]


def read_lls_output_lyrics(out_dir: str | Path) -> str:
    """Read the split lyrics .txt file generated by Local Lyric Splitter in out_dir."""
    folder = Path(out_dir)
    txt_files = sorted(
        (p for p in folder.iterdir() if p.is_file() and p.suffix.lower() == ".txt"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    if not txt_files:
        raise RuntimeError("Local Lyric Splitter exited without generating a .txt lyrics file.")

    txt_path = txt_files[0]
    raw = txt_path.read_bytes()
    try:
        content = raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        content = raw.decode("cp1252", errors="replace")

    content = content.replace("\r\n", "\n").replace("\r", "\n")

    if not content.strip():
        raise RuntimeError("Local Lyric Splitter generated an empty lyrics file.")
    return content


def run_local_lyric_splitter(
    exe_path: str | Path,
    artist: str,
    song: str,
    audio_path: str = "",
    timeout_sec: float = 120.0,
    process_holder: Optional[Dict[str, Any]] = None,
) -> str:
    """
    Run Local Lyric Splitter silently via CLI to fetch, clean, and syllable-split lyrics.
    Returns the resulting slash-delimited lyrics text.
    """
    exe = Path(exe_path)
    if not exe.is_file():
        raise FileNotFoundError(f"Local Lyric Splitter executable not found:\n{exe}")

    artist_clean = artist.strip()
    song_clean = song.strip()
    if not artist_clean or not song_clean:
        raise ValueError("Both Artist and Title are required to run Local Lyric Splitter.")

    creationflags = subprocess.CREATE_NO_WINDOW if sys.platform == "win32" else 0

    with tempfile.TemporaryDirectory(prefix="kbp_lls_") as tmp_dir:
        cmd = build_lls_cli_command(exe, artist_clean, song_clean, tmp_dir, audio_path=audio_path)
        proc = subprocess.Popen(
            cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            cwd=str(exe.parent),
            creationflags=creationflags,
        )
        if process_holder is not None:
            process_holder["proc"] = proc

        try:
            stdout, stderr = proc.communicate(timeout=timeout_sec)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.communicate()
            raise RuntimeError(
                f"Local Lyric Splitter timed out after {int(timeout_sec)} seconds."
            ) from None
        finally:
            if process_holder is not None:
                process_holder.pop("proc", None)

        if proc.returncode != 0:
            detail = "\n".join(part.strip() for part in (stderr, stdout) if part and part.strip()).strip()
            if detail:
                raise RuntimeError(
                    f"Local Lyric Splitter failed (exit code {proc.returncode}):\n{detail}"
                )
            raise RuntimeError(
                f"Local Lyric Splitter failed (exit code {proc.returncode}). "
                "Lyrics may not have been found for this Artist and Title."
            )

        return read_lls_output_lyrics(tmp_dir)
